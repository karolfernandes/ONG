    private void botaoCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoCadastrarActionPerformed
        // TODO add your handling code here:
        String tipo = campoTipo.getSelectedItem().toString();
        String problema = campoProblema.getText();

        // Aqui você deve já ter o ID do colaborador logado
        int idVoluntarioLogado = 1; // Substitua por sua lógica real

        if (tipo.isEmpty() || problema.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Preencha todos os campos.");
        } else {
            ChamadoModel chamado = new ChamadoModel();
            chamado.setTipo(tipo);
            chamado.setProblema(problema);
            chamado.setResolvido("não");
            chamado.setColaboradorIdVoluntario(colaborador.getIdColaborador());

            boolean cadastrado = controller.cadastrar(chamado);

            if (cadastrado) {
                JOptionPane.showMessageDialog(null, "Chamado cadastrado com sucesso!");
                campoTipo.setSelectedItem("Escolha uma opção");
                campoProblema.setText("");
            } else {
                JOptionPane.showMessageDialog(null, "Erro ao cadastrar o chamado.");
            }
        }

        carregarChamadosNaTabela();
    }//GEN-LAST:event_botaoCadastrarActionPerformed

    private void botaoResolvidoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botaoResolvidoActionPerformed
        // TODO add your handling code here:

        if (idChamadoSelecionado != 0) {
            boolean atualizado = controller.marcarComoResolvido(idChamadoSelecionado);
            if (atualizado) {
                JOptionPane.showMessageDialog(null, "Chamado resolvido!");
                carregarChamadosNaTabela();
                idChamadoSelecionado = 0; // limpa após uso
            }
        } else {
            JOptionPane.showMessageDialog(null, "Selecione um chamado antes.");
        }
        carregarChamadosNaTabela();
    }//GEN-LAST:event_botaoResolvidoActionPerformed

