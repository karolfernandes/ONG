    public void carregarChamadosNaTabela() {
        DefaultTableModel modelo = (DefaultTableModel) tabelaChamado.getModel();
        modelo.setRowCount(0); // Limpa a tabela

        List<ChamadoModel> chamados = controller.listarChamados();
        for (ChamadoModel ch : chamados) {
            modelo.addRow(new Object[]{
                ch.getTipo(),
                ch.getProblema(),
                ch.getResolvido(),
                ch.getIdChamado()
            });
        }
        tabelaChamado.getColumnModel().getColumn(3).setMinWidth(0);
        tabelaChamado.getColumnModel().getColumn(3).setMaxWidth(0);
        tabelaChamado.getColumnModel().getColumn(3).setWidth(0);
    }

    public void filtrarChamadoTabela(String textoPesquisa) {
        List<ChamadoModel> listaChamadoTabela = controller.pesquisarPorId(textoPesquisa);

        DefaultTableModel modelo = (DefaultTableModel) tabelaChamado.getModel();

        modelo.setRowCount(0);

        for (ChamadoModel c : listaChamadoTabela) {

            if (c.getTipo().toLowerCase().contains(textoPesquisa.toLowerCase())) {

                modelo.addRow(new Object[]{
                    c.getTipo(),
                    c.getProblema(),
                    c.getResolvido(),
                    c.getIdChamado()

                });
            }
        }

        tabelaChamado.getColumnModel().getColumn(3).setMinWidth(0);
        tabelaChamado.getColumnModel().getColumn(3).setMaxWidth(0);
        tabelaChamado.getColumnModel().getColumn(3).setWidth(0);

    }

